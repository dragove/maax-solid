export const MESSAGES: Record<Locale, Record<MessageKey, string>> = {
  "zh-CN": zh,
  "en-US": en,
};

export function t(locale: Locale, key: MessageKey): string {
  return MESSAGES[locale]?.[key] ?? MESSAGES["zh-CN"][key] ?? key;
}

export function pick(locale: Locale, value: LocalizedText): string {
  return locale === "en-US" ? value.en : value.zh;
}

export const enginePhaseKey = (phase: EnginePhase): MessageKey => {
  switch (phase) {
    case "idle":
      return "engine.idle";
    case "starting":
      return "engine.starting";
    case "ready":
      return "engine.ready";
    case "running":
      return "engine.running";
    case "crashed":
      return "engine.crashed";
    case "stopped":
      return "engine.stopped";
    default:
      return "engine.idle";
  }
};

export const runStatusKey = (status: RunStatus): MessageKey => {
  switch (status) {
    case "preparing":
    case "idle":
      return "tasks.pending";
    case "running":
      return "tasks.running";
    case "completed":
      return "tasks.completed";
    case "stopped":
      return "tasks.stopped";
    case "failed":
      return "tasks.failed";
    default:
      return "tasks.pending";
  }
};

export const runTaskStatusKey = (status: RunTaskStatus): MessageKey => {
  switch (status) {
    case "running":
      return "tasks.running";
    case "completed":
      return "tasks.completed";
    case "failed":
      return "tasks.failed";
    case "stopped":
      return "tasks.stopped";
    default:
      return "tasks.pending";
  }
};

export function formatClock(timestamp: number, locale: Locale): string {
  return new Intl.DateTimeFormat(locale, {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23",
  }).format(timestamp);
}
